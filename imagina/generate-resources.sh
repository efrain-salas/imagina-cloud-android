#!/bin/sh
# Generates the brand images of Imagina Cloud (app/src/imagina/res/drawable) from the SVG sources in
# imagina/brand. Run it after changing an SVG and commit the result. See IMAGINA.md.
set -e
cd "$(dirname "$0")/.."
OUT=app/src/imagina/res/drawable
OUT_NIGHT=app/src/imagina/res/drawable-night
VALUES=app/src/imagina/res/values
TOOL="python3 -I imagina/tools/svg_to_vector.py"
MARK=imagina/brand/imagina-cloud-mark.svg
WORDMARK=imagina/brand/imagina-cloud-wordmark.svg
WORDMARK_REVERSE=imagina/brand/imagina-cloud-wordmark-reverse.svg
mkdir -p "$OUT" "$OUT_NIGHT"

# Launcher icon (adaptive): the tile is the background, the glyph and its teal dot the foreground,
# centred inside the 66 dp safe zone of the 108 dp canvas.
$TOOL $MARK "$OUT/ic_launcher_foreground.xml" --width 108 --height 108 --viewport 108 108 --translate 18.75 25.25 --skip-rect
$TOOL $MARK "$OUT/ic_launcher_monochrome.xml" --width 108 --height 108 --viewport 108 108 --translate 18.75 25.25 --skip-rect --fill '#FFFFFFFF' --drop-fill '#1A1B25'
cat > "$OUT/ic_launcher_background.xml" <<'XML'
<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by imagina/generate-resources.sh: the brand tile colour (brand-ink) -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp" android:height="108dp" android:viewportWidth="108" android:viewportHeight="108">
    <path android:fillColor="#1A1B25" android:pathData="M0,0h108v108h-108Z" />
</vector>
XML

# Nextcloud's own launcher icons are PNGs per density in app/src/main/res/mipmap-*dpi. Android 8 and later (minSdk is 28)
# always picks the adaptive icon of mipmap-anydpi, but the PNGs would still ship in the APK: the same adaptive icon under
# each density replaces them (a resource of the flavor with the same name and density wins, whatever its file type).
for DENSITY in mdpi hdpi xhdpi xxhdpi xxxhdpi; do
    mkdir -p "app/src/imagina/res/mipmap-$DENSITY"
    cp app/src/imagina/res/mipmap-anydpi/ic_launcher.xml "app/src/imagina/res/mipmap-$DENSITY/ic_launcher.xml"
done

# Wordmark «imagina /cloud» (cream grounds) and its reverse for the dark theme (drawable-night): the logo of
# the first screen, the splash and the drawer header. 618.5 x 98 in the SVG; 180 x 28.52 dp (never under 20 dp high).
$TOOL $WORDMARK "$OUT/imagina_cloud_wordmark.xml" --width 180 --height 28.52
$TOOL $WORDMARK_REVERSE "$OUT_NIGHT/imagina_cloud_wordmark.xml" --width 180 --height 28.52

# The images Nextcloud shows as its logo (first screen, splash, drawer header) are the wordmark in Imagina Cloud.
cat > "$VALUES/brand_images.xml" <<'XML'
<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by imagina/generate-resources.sh: the images Nextcloud uses as its logo are Imagina Cloud's wordmark
     (drawable and drawable-night/imagina_cloud_wordmark.xml). The icon is kept for the launcher and notifications. -->
<resources>
    <drawable name="logo">@drawable/imagina_cloud_wordmark</drawable>
    <drawable name="nextcloud_splash_logo">@drawable/imagina_cloud_wordmark</drawable>
    <drawable name="nextcloud_logo">@drawable/imagina_cloud_wordmark</drawable>
</resources>
XML

# Status bar notification icon: white silhouette.
$TOOL $MARK "$OUT/notification_icon.xml" --width 24 --height 24 --skip-rect --fill '#FFFFFFFF' --drop-fill '#1A1B25'

echo "Generated in $OUT"
