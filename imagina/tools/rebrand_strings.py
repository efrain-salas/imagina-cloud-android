#!/usr/bin/env python3
"""Writes, for every language of the app, the texts of app/src/main/res/values*/strings.xml that say
"Nextcloud" with the brand name of Imagina Cloud instead, into app/src/imagina/res/values*/strings_rebrand.xml
(see IMAGINA.md, «Textos»). Run it again after updating Nextcloud. Only the capitalised word is replaced, so
links such as nextcloud.com keep working. Multi-line strings and plurals are reported, not changed.

Usage: rebrand_strings.py BRAND_NAME
"""
import pathlib
import re
import sys

brand = sys.argv[1]
root = pathlib.Path(__file__).resolve().parents[2]
main_res = root / 'app/src/main/res'
flavor_res = root / 'app/src/imagina/res'
single = re.compile(r'^\s*<string name="([^"]+)"([^>]*)>(.*)</string>\s*$')
total = 0

for source in sorted(main_res.glob('values*/strings.xml')):
    overrides, skipped = [], []
    for line in source.read_text(encoding='utf-8').splitlines():
        if 'Nextcloud' not in line:
            continue
        match = single.match(line)
        if not match:
            skipped.append(line.strip()[:80])
            continue
        name, attributes, text = match.groups()
        overrides.append(f'    <string name="{name}"{attributes}>{text.replace("Nextcloud", brand)}</string>')

    target = flavor_res / source.parent.name / 'strings_rebrand.xml'
    if overrides:
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(
            '<?xml version="1.0" encoding="utf-8"?>\n'
            '<!-- Generated by imagina/tools/rebrand_strings.py from ' + str(source.relative_to(root)) + ': do not edit -->\n'
            '<resources xmlns:tools="http://schemas.android.com/tools" tools:ignore="MissingTranslation">\n'
            + '\n'.join(overrides) + '\n</resources>\n',
            encoding='utf-8',
        )
        total += len(overrides)
    elif target.exists():
        target.unlink()
    for line in skipped:
        print(f'{source.parent.name}: not changed (not a one-line <string>): {line}')

print(f'{total} texts rebranded as "{brand}"')
